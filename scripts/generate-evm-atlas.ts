function resolveChainScript(registryChains: RegistryChain[], data: AtlasOverlay): string {
  const cases = registryChains.map((chain) => {
    const pattern = overlayRow(data, chain).chainscoutNamePattern ?? chain.name;
    return `    ${chain.chainId}) printf '%s\\n' '${singleQuote(pattern)}' ;;`;
  });
  const unsafeCases = registryChains
    .filter((chain) => overlayRow(data, chain).blockscout.status === "unsafe")
    .map((chain) => {
      const notes = overlayRow(data, chain).blockscout.notes ?? "";
      return `    ${chain.chainId}) printf '%s\\n' '${singleQuote(notes)}' ;;`;
    });
  const unsafeShellcheckDirectives = registryChains.some(
    (chain) =>
      overlayRow(data, chain).blockscout.status === "unsafe" &&
      (overlayRow(data, chain).blockscout.notes?.includes("`") ?? false),
  )
    ? ["  # shellcheck disable=SC2016"]
    : [];

  return [
    "#!/bin/bash",
    "# resolve-chain.sh - Resolve a target chain_id to its Blockscout instance via Chainscout.",
    "#",
    `# ${generatedBy}`,
    "#",
    "# Usage: resolve-chain.sh <target_chain_id>",
    "#",
    "# Outputs key=value lines on stdout:",
    "#   chain_id=<int>",
    "#   name=<string>",
    "#   native_currency=<symbol>",
    "#   instance_url=<url, ends in />",
    "#   hosted_by=<blockscout|other>",
    "#   is_testnet=<true|false>",
    "#   layer=<int|>",
    "#   rollup_type=<string|>",
    "#",
    "# No API key required. Source: https://chains.blockscout.com/",
    "# Scope is intentionally limited to skills/evm-atlas/references/generated/target-mainnets.json.",
    "",
    "set -eu",
    "",
    'if [ $# -lt 1 ] || [ -z "${1:-}" ]; then',
    '  echo "Usage: resolve-chain.sh <chain_id>" >&2',
    "  exit 1",
    "fi",
    "",
    'chain_id="$1"',
    "",
    "target_name_pattern() {",
    '  case "$1" in',
    ...cases,
    "    *)",
    "      return 1",
    "      ;;",
    "  esac",
    "}",
    "",
    'expected_pattern=$(target_name_pattern "$chain_id") || {',
    '  echo "Error: chain_id=$chain_id is outside the evm-atlas target list." >&2',
    '  echo "Ask the user to file a feature request in https://github.com/PaulRBerg/agent-skills" >&2',
    "  exit 2",
    "}",
    "",
    "unsafe_reason() {",
    ...unsafeShellcheckDirectives,
    '  case "$1" in',
    ...unsafeCases,
    "    *)",
    "      return 1",
    "      ;;",
    "  esac",
    "}",
    "",
    'if reason=$(unsafe_reason "$chain_id"); then',
    '  echo "Error: chain_id=$chain_id is marked unsafe in the evm-atlas overlay." >&2',
    '  echo "Reason: $reason" >&2',
    "  exit 1",
    "fi",
    "",
    'resp=$(curl -fsS "https://chains.blockscout.com/api/chains/$chain_id" 2>/dev/null) || {',
    '  echo "Error: Chainscout request failed for chain_id=$chain_id" >&2',
    "  exit 1",
    "}",
    "",
    'sval() { printf \'%s\' "$resp" | grep -o "\\"$1\\":\\"[^\\"]*\\"" | head -1 | sed \'s/.*:"\\(.*\\)"/\\1/\'; }',
    'nval() { printf \'%s\' "$resp" | grep -o "\\"$1\\":[0-9]*" | head -1 | grep -o \'[0-9]*\'; }',
    'bval() { printf \'%s\' "$resp" | grep -oE "\\"$1\\":(true|false)" | head -1 | sed \'s/.*://\'; }',
    "",
    'name=$(sval "name")',
    'if [ -z "$name" ]; then',
    '  echo "Error: chain_id=$chain_id not found in Chainscout" >&2',
    "  exit 1",
    "fi",
    'if ! printf \'%s\' "$name" | grep -Eiq "$expected_pattern"; then',
    '  echo "Error: Chainscout returned name=$name for target chain_id=$chain_id; expected match=$expected_pattern" >&2',
    '  echo "Refusing to use a non-target Chainscout registry match." >&2',
    "  exit 1",
    "fi",
    "",
    'native=$(sval "native_currency")',
    '# "url" only appears inside explorers[]; the first is the primary explorer.',
    'instance=$(printf \'%s\' "$resp" | grep -o \'"url":"[^"]*"\' | head -1 | sed \'s/.*:"\\(.*\\)"/\\1/\')',
    'hosted=$(sval "hostedBy")',
    'testnet=$(bval "isTestnet")',
    'layer=$(nval "layer")',
    'rollup=$(sval "rollupType")',
    "",
    "cat <<EOF",
    "chain_id=$chain_id",
    "name=$name",
    "native_currency=$native",
    "instance_url=$instance",
    "hosted_by=$hosted",
    "is_testnet=$testnet",
    "layer=$layer",
    "rollup_type=$rollup",
    "EOF",
    "",
  ].join("\n");
}

function groupBy<T>(items: T[], keyFn: (item: T) => string): Record<string, T[]> {
  const result: Record<string, T[]> = {};
  for (const item of items) {
    const key = keyFn(item);
    result[key] ??= [];
    result[key].push(item);
  }
  return result;
}

function overlayRow(data: AtlasOverlay, chain: Pick<RegistryChain, "slug">): ChainOverlay {
  const row = data.chains[chain.slug];
  if (!row) fail(`Missing overlay row: ${chain.slug}.`);
  return row;
}

function markdownTable(headers: string[], rows: MarkdownCell[][]): string {
  const widths = headers.map((header, index) =>
    Math.max(header.length, ...rows.map((row) => String(row[index] ?? "").length)),
  );
  const formatRow = (row: MarkdownCell[]) =>
    `| ${row.map((cell, index) => String(cell ?? "").padEnd(widths[index] ?? 0)).join(" | ")} |`;
  return [formatRow(headers), formatRow(widths.map((width) => "-".repeat(width))), ...rows.map(formatRow)].join("\n");
}

function code(value: number | string): string {
  return `\`${value}\``;
}

function singleQuote(value: string): string {
  return value.replaceAll("'", "'\\''");
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function commandErrorMessage(error: unknown): string {
  if (
    error !== null &&
    typeof error === "object" &&
    "stderr" in error &&
    typeof error.stderr === "string" &&
    error.stderr.trim()
  ) {
    return error.stderr.trim();
  }
  return errorMessage(error);
}

function fail(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}
